"""Render a secure-code-agent Markdown report as the published example report.

    python tools/render_example_report.py secure-code-report.md

writes `docs/example-report.html`: one self-contained page (inline styles, no
scripts, nothing loaded from elsewhere) that GitHub Pages serves at
https://secure-code-agent.techportfolio.monster/example-report.html.
Regenerate it with each release, from a self-audit run at that release, so the
page states the version it was made by.

The report records where each scanner ran from, which is a path on the machine
that ran it. Those paths are shortened to the executable's name. The report
also quotes source that names local-path prefixes as text; the slashes of
those are written as character references, so the page reads exactly as the
source does and the published file carries no path from any machine.
"""

from __future__ import annotations

import html
import re
import sys
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "example-report.html"
STYLES = Path(__file__).with_name("render_docs.css")

GENERATED_BANNER = (
    "<!-- @generated by tools/render_example_report.py from a secure-code-agent "
    "Markdown report: regenerate it, do not edit this page. -->"
)

#: Prefixes that only ever begin a path on one particular machine.
_LOCAL_PREFIXES = ("/private/tmp", "/private/var", "/var/folders", "/Users", "/home")
_LOCAL_PATH = re.compile(
    r"(?:" + "|".join(re.escape(p) for p in _LOCAL_PREFIXES) + r")/[^\s`|)\"'<>]+"
)


def _shorten(match: re.Match) -> str:
    return match.group(0).rstrip("/").rsplit("/", 1)[-1]


def scrub(text: str) -> str:
    """Shorten every local path to its last component."""
    return _LOCAL_PATH.sub(_shorten, text)


def _encode_prefixes(page: str) -> str:
    """Write the slashes of any remaining local-path prefix as references."""
    for prefix in (*_LOCAL_PREFIXES, "C:\\"):
        page = page.replace(prefix, prefix.replace("/", "&#47;").replace("\\", "&#92;"))
    return page


def render(report: str) -> str:
    converter = markdown.Markdown(extensions=["tables", "fenced_code", "sane_lists"])
    lines = scrub(report).splitlines(keepends=True)
    title = next((line[2:].strip() for line in lines if line.startswith("# ")), "Report")
    body_md = "".join(line for line in lines if not line.startswith("# "))
    body = converter.convert(body_md)
    body = body.replace("<table>", '<div class="table-wrap"><table>').replace(
        "</table>", "</table></div>"
    )
    css = STYLES.read_text(encoding="utf-8")
    page = f"""{GENERATED_BANNER}
<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Example report · secure-code-agent</title>
<style>{css}
.single{{max-width:1100px;margin:0 auto;padding:32px 24px 80px}}
@media (max-width:600px){{.single{{padding:20px 16px 60px}}}}</style></head><body>
<div class="top"><div class="top-inner"><a class="brand" href="index.html">secure-code-agent</a>
<nav><a href="html/index.html">Documentation</a></nav></div></div>
<main class="single"><div class="meta">Example report: secure-code-agent auditing its own repository</div>
<h1>{html.escape(title)}</h1>{body}
<footer>Generated by secure-code-agent from its own repository. The full report, unedited apart
from local paths shortened to the scanner's name.</footer></main></body></html>
"""
    return _encode_prefixes(page)


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print("usage: render_example_report.py REPORT.md", file=sys.stderr)
        return 2
    OUT.write_text(render(Path(argv[0]).read_text(encoding="utf-8")), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
